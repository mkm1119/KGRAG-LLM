def old(name):
    return json.load(open(os.path.join(SEC, '_old', name + '.json'), encoding='utf-8'))


def old_table(items, label):
    v = [v for k, v in items if k == 'TABLE' and v['label'] == label][0]
    v = json.loads(json.dumps(v))
    head = v['rows'][0]
    if '게재처 유형' in head:                                  # 게재처 유형은 발주처가 볼 내용이 아니므로 뺀다
        j = head.index('게재처 유형')
        v['rows'] = [r[:j] + r[j + 1:] for r in v['rows']]
        v['widths'] = v['widths'][:j] + v['widths'][j + 1:]
        if v.get('align'): v['align'] = v['align'][:j] + v['align'][j + 1:]
        if '게재처' in v.get('note', ''): v.pop('note')
    v['rows'] = [[re.sub(r'논문에 제시되지 않음|미제시|미기재', '-', str(c)) for c in r] for r in v['rows']]
    return ['TABLE', v]


def old_detail(items):
    """이전 판 '라. 주요 사례 상세 비교'에서 사례별 설명과 그림 자리, 비교표를 가져온다."""
    out, on, skip_sq, skip_ci, tail = [], False, False, False, False
    for k, v in items:
        if k == 'H4':
            on = v.startswith('라.'); continue
        if not on: continue
        if k == 'H5':
            tail = '비교' in v                                 # '(4) 세 사례의 비교'는 표만 남긴다
            skip_sq = skip_ci = False
            if not tail: out.append([k, v])
            continue
        if k in ('TABLE', 'FIGPLACE'):
            out.append([k, v]); continue
        if tail or k == 'BODY': continue
        if k == 'SQ':
            skip_sq = v.startswith('선정 기준'); skip_ci = False
            if not skip_sq: out.append([k, v])
            continue
        if skip_sq: continue
        if k == 'CI':
            skip_ci = bool(BAD.search(v))
            if not skip_ci: out.append([k, v])
        elif k == 'DS':
            if not skip_ci and not BAD.search(v): out.append([k, v])
    res = []
    for i, (k, v) in enumerate(out):                           # 내용이 모두 빠진 □ 는 지운다
        if k == 'SQ' and (i + 1 == len(out) or out[i + 1][0] in ('SQ', 'H5', 'TABLE', 'FIGPLACE')): continue
        res.append([k, v])
    return res


def build(text, src=None, tables=None):
    out = []
    for ln in text.strip().split('\n'):
        ln = ln.strip()
        if not ln: continue
        tag, _, rest = ln.partition(' ')
        if tag == '#3': out.append(['H3', rest])
        elif tag == '#4': out.append(['H4', rest])
        elif tag == 'B': out.append(['BODY', rest])
        elif tag == '□': out.append(['SQ', rest])
        elif tag == '◦': out.append(['CI', rest])
        elif tag == '-': out.append(['DS', rest])
        elif tag == '@T': out.append(old_table(src, rest))
        elif tag == '@D': out += old_detail(src)
        elif tag == '@N': out.append(['TABLE', tables[rest]])
        else: raise ValueError(ln)
    return out


def T(label, caption, widths, rows, align=None):
    return {'label': label, 'caption': caption, 'widths': widths, 'align': align or (['c'] + ['l'] * (len(widths) - 1)), 'rows': rows}


