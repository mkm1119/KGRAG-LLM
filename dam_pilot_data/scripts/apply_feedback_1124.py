# ------------------------------------------------------------------ 1) 장 번호
log = []
up = lambda m: str(int(m.group(1)) + 1)


def shift(s, where):
    o = s
    s = re.sub(r'(?<![\w.\-])([1-4])(?=\.\d\.\d{1,2}(?![\d.]))', up, s)              # 1.1.4 -> 2.1.4
    s = re.sub(r'(?<![\w.\-])([1-4])(?=\.\d절)', up, s)                              # 2.2절 -> 3.2절
    s = re.sub(r'(?<![\d,.])([1-5])·([1-5])장', lambda m: '%d·%d장' % (int(m.group(1)) + 1, int(m.group(2)) + 1), s)
    hw = re.compile(r'(GB|H100|NVL|A6000|A800|GPU|\d{4}) $')                       # 'A6000 2장'은 장비 수량이지 장 번호가 아니다
    s = re.sub(r'(?<![\d,.·])([1-5])(?=장(?:[과와의에은을,. )]|$))', lambda m: m.group(1) if hw.search(m.string[:m.start()]) else up(m), s)   # 3장과 4장 -> 4장과 5장
    if s != o:
        log.append('%s: %s -> %s' % (where, o[:70], s[:70]))
    return s


def walk(v, where):
    if isinstance(v, str):
        return shift(v, where)
    if isinstance(v, list):
        return [walk(x, where) for x in v]
    if isinstance(v, dict):
        return {k: (walk(x, where) if k != 'label' else x) for k, x in v.items()}
    return v


