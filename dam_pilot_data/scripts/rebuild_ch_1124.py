def blocks(L, kind):
    """kind(H3 또는 H4) 제목을 기준으로 (앞부분, [(제목, 내용)...])로 나눈다."""
    idx = [i for i, x in enumerate(L) if x[0] == kind]
    return L[:idx[0]] if idx else L, [(L[i][1], L[i + 1:j]) for i, j in zip(idx, idx[1:] + [len(L)])]


def table(L, label):
    return [x[1] for x in L if x[0] == 'TABLE' and x[1]['label'] == label][0]


