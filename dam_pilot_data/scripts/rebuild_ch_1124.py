def merge_case(f, lst, c1, c2, cols, caption, label, widths, lead, extra=()):
    L = D[f]
    head, bl = blocks(L, 'H4')
    b = {t[0]: c for t, c in bl}
    tl, t1, t2 = table(L, lst), table(L, c1), table(L, c2)
    h1, h2 = t1['rows'][0], t2['rows'][0]
    r1 = {r[0]: dict(zip(h1, r)) for r in t1['rows'][1:]}
    r2 = {r[0]: dict(zip(h2, r)) for r in t2['rows'][1:]}
    hl = tl['rows'][0]
    rows = [['번호', '사례(출처)', '대상 분야'] + [c[0] for c in cols]]
    rest = []
    for r in tl['rows'][1:]:
        d = dict(zip(hl, r))
        if d['번호'] not in r1:
            rest.append(d); continue
        src = dict(r1[d['번호']]); src.update(r2[d['번호']])
        rows.append([d['번호'], d['사례'] + '\n' + d['출처'], d['대상 분야']] + [' / '.join(src[k] for k in c[1]) for c in cols])
    merged = ['TABLE', {'label': label, 'caption': caption, 'widths': widths, 'align': ['c'] + ['l'] * (len(rows[0]) - 1), 'rows': rows}]
    na = [['BODY', lead], merged] + list(extra(rest, b['나']) if extra else []) + b['라']
    D[f] = head + [['H4', '가. 구성 방식']] + b['가'] + [['H4', '나. 사례 비교']] + na + [['H4', '다. 주요 사례의 구성과 결과']] + b['다'] + [['H4', '라. 댐 운영 적용 방향']] + b['마']
    return len(rows) - 1, len(rest)


