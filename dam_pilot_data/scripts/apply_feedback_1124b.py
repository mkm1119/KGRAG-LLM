log = []
NAV = re.compile(r'(에서|에) (따로 )?(다룬다|다루었다)\.$|상세히 정리하였다\.$|나누어 정리하였다\.$|묶어 정리하였다\.$|표시하였다\.$|표기하였다\.$|^이를 근거로 [^.]*정리하였다\.$'
                 r'|^비교 결과를 근거로 [^.]*정리하였다\.$|(을|를) 정리하였다\.$|종합하였다\.$')
NAV_ITEM = re.compile(r'(에서|에|[0-9]) (따로 )?(다룸|정리|제시)$|나누어 정리$|나란히 정리$|아키텍처\(안\)로 정리$|같은 항목으로 비교$')
josa = lambda w, a, b: a if (ord(w[-1]) - 0xAC00) % 28 and '가' <= w[-1] <= '힣' else b


def clean_body(f, i, v, nxt):
    o = v
    if v.startswith('같은 항목으로 비교한 결과는 ⟦표:') and nxt and nxt[0] == 'TABLE':
        cap = nxt[1]['caption']
        return '%s%s ⟦표:%s⟧와 같다.' % (cap, josa(re.sub(r'\([^)]*\)$', '', cap) or cap, '은', '는'), nxt[1]['label'])
    v = re.sub(r'(이었|였|었|았)으며, 이를 근거로 [^.]*?정리하였다\.', r'\1다.', v)
    sents = re.split(r'(?<=다\.)\s+', v)
    if '상세히 정리하였다' in v:
        sents = [s for s in sents if '⟦' in s]
    out = []
    for s in sents:
        if '⟦' in s:                                             # 표·그림을 가리키는 문장은 '○○은 표와 같다'로
            s = re.sub(r'⟧에, ', '⟧, ', s)
            s = re.sub(r'(\S)(을|를) (⟦[^⟧]+⟧(?:과 ⟦[^⟧]+⟧)?)에 (?:나란히 )?(?:정리|비교|제시|종합)하였다\.', lambda m: m.group(1) + ('은' if m.group(2) == '을' else '는') + ' ' + m.group(3) + '와 같다.', s)
            s = re.sub(r'⟧에 (?:정리|비교|제시|종합)하였다\.', '⟧와 같다.', s)
            out.append(s)
        elif NAV.search(s) and '정하고' not in s:
            continue
        else:
            out.append(s)
    v = ' '.join(out)
    if v != o:
        log.append('%s %d\n    - %s\n    + %s' % (f, i, o[:300], v[:300] or '(삭제)'))
    return v


for f, items in D.items():
    new = []
    for i, (kind, v) in enumerate(items):
        if kind == 'TABLE':
            v = dict(v); v['note'] = None
        elif kind == 'BODY':
            v = clean_body(f, i, v, items[i + 1] if i + 1 < len(items) else None)
            if not v: continue
        elif kind in ('CI', 'DS') and NAV_ITEM.search(v):
            log.append('%s %d\n    - %s\n    + (삭제)' % (f, i, v)); continue
        new.append([kind, v])
    out = []                                                     # 아래 항목이 없어진 □ 제목을 뺀다
    for j, it in enumerate(new):
        if it[0] == 'SQ' and (j + 1 == len(new) or new[j + 1][0] in ('SQ', 'H3', 'H4', 'H5')):
            log.append('%s\n    - □ %s\n    + (삭제)' % (f, it[1])); continue
        out.append(it)
    D[f] = out
    json.dump(out, open(os.path.join(SEC, f + '.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('\n'.join(log))
