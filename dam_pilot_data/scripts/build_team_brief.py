def run(text, sz=None, b=False, color=None, i=False):
    pr = ('<w:b/>' if b else '') + ('<w:i/>' if i else '') + ('<w:color w:val="%s"/>' % color if color else '') + ('<w:sz w:val="%d"/><w:szCs w:val="%d"/>' % (sz, sz) if sz else '') + LANG
