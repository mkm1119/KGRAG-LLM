def md_to_blocks(path):
    out = []
    for line in open(path, encoding='utf-8').read().replace('**', '').replace('`', '').split('\n'):
        if not line.strip():
            continue
        if line.startswith('# '):
            continue
        if line.startswith('## '):
            out.append(label(line[3:].strip()))
        elif line.startswith('- '):
            out.append(li(line[2:].strip()))
        else:
            out.append(para(line.strip()))
    return out


