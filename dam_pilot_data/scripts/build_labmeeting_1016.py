def bundle_display(b):
    i = b.index('[EVI:LAW:별표3]'); k = b.index('원문:\n', i) + len('원문:\n'); j = b.index('\n\n[근거 3.')
    b = b[:k] + '  (별표3 원문 전체)' + b[j:]
    out, cnt = [], {'OPR': 0, 'APR': 0}
    for l in b.split('\n'):
        key = 'OPR' if l.startswith('[OPR') else 'APR' if l.startswith('[APR') else None
        if key:
            cnt[key] += 1
            if cnt[key] > 3:
                if cnt[key] == 4:
                    out.append('  …')
                continue
        out.append(l)
    return '\n'.join(out)


